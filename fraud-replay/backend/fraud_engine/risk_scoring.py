"""Баллы правил — эвристический приоритет проверки, не вероятность."""
WEIGHTS = {"large": 35, "burst": 25, "chain": 60, "fanout": 40}
REASONS = {
    "large": "Необычно крупный перевод относительно предыдущей истории отправителя",
    "burst": "Серия из не менее 4 переводов отправителя за 5 минут",
    "chain": "Быстрая цепочка из не менее 3 переводов с сохранением 70–100% суммы на каждом шаге",
    "fanout": "Распределение средств не менее чем 3 разным получателям за 10 минут",
}


def score_rules(rules):
    score = min(100, sum(WEIGHTS[r] for r in set(rules)))
    return score, "high" if score >= 60 else "medium" if score >= 30 else "low"
